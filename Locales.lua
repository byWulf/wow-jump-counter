-- Russian plural: 1 прыжок, 2-4 прыжка, 5+ прыжков (11-14 always прыжков)
local function RussianJumps(n, s)
    local m10, m100 = n % 10, n % 100
    if m10 == 1 and m100 ~= 11 then return s .. " прыжок" end
    if m10 >= 2 and m10 <= 4 and (m100 < 12 or m100 > 14) then return s .. " прыжка" end
    return s .. " прыжков"
end

